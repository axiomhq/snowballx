package greek_test

import (
	"testing"

	"github.com/blevesearch/snowballstem"
	"github.com/axiomhq/snowballx/greek"
)

// Every 1,500th pair of snowball-data greek/voc.txt and greek/output.txt.
// The whole 90,727-word list matched when the package was generated.
func TestStemMatchesSnowballData(t *testing.T) {
	for _, tc := range []struct{ word, want string }{
		{"αυτοκινηση", "αυτοκινησ"},
		{"ένατης", "ενατ"},
		{"αγώνος", "αγων"},
		{"ακροπτερύγια", "ακροπτερυγ"},
		{"ανέλαβε", "ανελαβ"},
		{"ανασηκωμένα", "ανασηκωμεν"},
		{"αντεκδίκηση", "αντεκδικησ"},
		{"απαιτηθεί", "απαιτ"},
		{"απομονώνει", "απομονων"},
		{"αρμοστείας", "αρμοστει"},
		{"αυταρχικό", "αυταρχ"},
		{"βασίλεψαν", "βασιλεψ"},
		{"βρικόλακες", "βρικολακ"},
		{"γλιστράει", "γλιστρ"},
		{"δεινόσαυροι", "δεινοσαυρ"},
		{"διαιρεμένη", "διαιρεμεν"},
		{"διδάχτηκαν", "διδαχτ"},
		{"δούκισσα", "δουκισσ"},
		{"εθνότητας", "εθνοτητ"},
		{"εκτεταμένη", "εκτεταμεν"},
		{"ενδεχόμενες", "ενδεχομεν"},
		{"εξαφανίζονται", "εξαφανιζ"},
		{"επανενώσεις", "επανενωσ"},
		{"επιτείνει", "επιτειν"},
		{"ευλυγισίας", "ευλυγισι"},
		{"ημερών", "ημερ"},
		{"θυμηθούμε", "θυμ"},
		{"ιχθύος", "ιχθυ"},
		{"κανέλα", "κανελ"},
		{"καταρρίπτεται", "καταρριπτ"},
		{"κιονοστοιχίας", "κιονοστοιχι"},
		{"κουνούπια", "κουνουπ"},
		{"κόμικς", "κομικσ"},
		{"λογιστική", "λογιστικ"},
		{"μαχαιρώθηκε", "μαχαιρ"},
		{"μετατόπισή", "μετατοπισ"},
		{"μορφωμάτων", "μορφωμ"},
		{"νεοφιλελευθερισμός", "νεοφιλελευθερ"},
		{"ξεσήκωσαν", "ξεσηκωσ"},
		{"οξειδοαναγωγή", "οξειδοαναγωγ"},
		{"πέσιμο", "πεσιμ"},
		{"παρακάμπτεται", "παρακαμπτ"},
		{"πενίας", "πενι"},
		{"πιστοί", "πιστ"},
		{"πολυκαταστήματος", "πολυκαταστημ"},
		{"προικισμένα", "προικισμεν"},
		{"προφήτεψε", "προφητεψ"},
		{"ράμπα", "ραμπ"},
		{"σελινιών", "σελιν"},
		{"σπάνιου", "σπαν"},
		{"στρώματα", "στρωμ"},
		{"συνήθη", "συνηθ"},
		{"συστηματοποιήθηκε", "συστηματοποι"},
		{"ταπετσαρία", "ταπετσαρ"},
		{"τουλίπες", "τουλιπ"},
		{"τόπο", "τοπ"},
		{"υποδιαιρείται", "υποδιαιρειτα"},
		{"φασματικούς", "φασματικ"},
		{"φυσικότητας", "φυσικοτητ"},
		{"χλόη", "χλο"},
		{"ωε", "ωε"},
	} {
		env := snowballstem.NewEnv(tc.word)
		greek.Stem(env)
		if got := env.Current(); got != tc.want {
			t.Errorf("Stem(%q) = %q, want %q", tc.word, got, tc.want)
		}
	}
}
